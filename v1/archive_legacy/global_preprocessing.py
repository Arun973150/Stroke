    def run(self, train_ratio=0.7, val_ratio=0.15):
        """Run the complete preprocessing pipeline"""
        print("="*70)
        print("ISLES 2022 - GLOBAL PREPROCESSING PIPELINE")
        print("="*70)

        # Discover cases
        cases = self.discover_cases()
        if len(cases) == 0:
            raise ValueError("No cases found! Check raw_data_path")

        print(f"\nTotal cases found: {len(cases)}")

        # Calculate split sizes
        n_train = int(len(cases) * train_ratio)
        n_val = int(len(cases) * val_ratio)

        train_cases = cases[:n_train]
        val_cases = cases[n_train:n_train + n_val]
        test_cases = cases[n_train + n_val:]

        print(f"\nData split:")
        print(f"  Train: {len(train_cases)} cases ({train_ratio*100:.0f}%)")
        print(f"  Val:   {len(val_cases)} cases ({val_ratio*100:.0f}%)")
        print(f"  Test:  {len(test_cases)} cases ({(1-train_ratio-val_ratio)*100:.0f}%)")

        # Process all cases
        print(f"\nProcessing cases...")
        idx = 1

        for split, case_list in [('train', train_cases), ('val', val_cases), ('test', test_cases)]:
            print(f"\nProcessing {split} split ({len(case_list)} cases)...")

            for subject_id in tqdm(case_list, desc=f"  {split}"):
                try:
                    metadata = self.process_case(subject_id, idx, split)
                    self.case_records.append(metadata)
                    idx += 1
                except Exception as e:
                    print(f"\n  ✗ Failed: {subject_id} - {str(e)}")
                    self.failed_cases.append({
                        'subject_id': subject_id,
                        'split': split,
                        'error': str(e)
                    })

        # Create summary files
        print(f"\nCreating summary files...")

        # Save case records
        df_records = pd.DataFrame(self.case_records)
        df_records.to_csv(self.metadata_path / 'case_records.csv', index=False)
        print(f"  ✓ case_records.csv saved ({len(df_records)} cases)")

        # Save failed cases if any
        if self.failed_cases:
            df_failed = pd.DataFrame(self.failed_cases)
            df_failed.to_csv(self.metadata_path / 'failed_cases.csv', index=False)
            print(f"  ⚠ failed_cases.csv saved ({len(df_failed)} failures)")

        # Create dataset.json and datalist.json
        self.create_dataset_json()
        print(f"  ✓ dataset.json created")

        self.create_monai_datalist()
        print(f"  ✓ datalist.json created")

        # Print statistics
        print("\n" + "="*70)
        print("PREPROCESSING COMPLETE")
        print("="*70)
        print(f"\nSuccessfully processed: {len(self.case_records)} / {len(cases)} cases")
        print(f"Failed cases: {len(self.failed_cases)}")

        if len(self.case_records) > 0:
            print(f"\nLesion size distribution:")
            print(df_records['lesion_category'].value_counts().to_string())
            print(f"\nLesion volume statistics:")
            print(f"  Mean: {df_records['lesion_volume_ml'].mean():.2f} mL")
            print(f"  Median: {df_records['lesion_volume_ml'].median():.2f} mL")
            print(f"  Min: {df_records['lesion_volume_ml'].min():.2f} mL")
            print(f"  Max: {df_records['lesion_volume_ml'].max():.2f} mL")

        print(f"\nOutput directory: {self.output_path}")
        print(f"  ├── nnunet_format/  (for nnU-Net v2)")
        print(f"  ├── monai_format/   (for Swin-UNETR & SegResNet)")
        print(f"  └── metadata/       (statistics & case info)")

        # Run verification
        self.verify_output()

        return len(self.case_records), len(self.failed_cases)


