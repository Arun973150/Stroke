def verify_nnunet_dataset(nnunet_path, num_modalities=3):
    nnunet_path = Path(nnunet_path)

    imagesTr = nnunet_path / "imagesTr"
    labelsTr = nnunet_path / "labelsTr"
    imagesTs = nnunet_path / "imagesTs"
    labelsTs = nnunet_path / "labelsTs"

    print("\n" + "="*70)
    print("NNUNET DATASET VERIFICATION (FULL MODALITY CHECK)")
    print("="*70)

    def check_split(images_dir, labels_dir, split_name):
        image_files = sorted(images_dir.glob("*_0000.nii.gz"))

        print(f"\n[{split_name}]")
        print(f"Total cases detected: {len(image_files)}")

        missing_cases = []

        for img0 in image_files:
            case_id = img0.name.split("_0000")[0]

            # Check all modalities
            modality_ok = True
            for m in range(num_modalities):
                mod_file = images_dir / f"{case_id}_{m:04d}.nii.gz"
                if not mod_file.exists():
                    modality_ok = False
                    print(f"  ❌ Missing modality {m:04d} for {case_id}")

            # Check label
            label_file = labels_dir / f"{case_id}.nii.gz"
            if not label_file.exists():
                modality_ok = False
                print(f"  ❌ Missing label for {case_id}")

            if not modality_ok:
                missing_cases.append(case_id)

        if not missing_cases:
            print(f"  ✅ All {split_name} cases are complete")
        else:
            print(f"\n  ⚠ Incomplete cases in {split_name}: {len(missing_cases)}")
            for c in missing_cases:
                print(f"    - {c}")

        return len(missing_cases)

    # Run checks
    missing_tr = check_split(imagesTr, labelsTr, "TRAIN")
    missing_ts = check_split(imagesTs, labelsTs, "TEST")

    print("\n" + "="*70)
    if missing_tr == 0 and missing_ts == 0:
        print("✅ DATASET VERIFICATION PASSED — READY FOR nnU-Net v2")
    else:
        print("❌ DATASET VERIFICATION FAILED — FIX MISSING FILES")

    print("="*70)

